const dictionaries: Record<string, Dict> = { en, pt };

interface I18nContextValue {
  language: string;
  t: (key: string, params?: Record<string, string | number>) => string;
  plural: (n: number, wordKey: 'word.concept' | 'word.question') => string;
}

const I18nContext = createContext<I18nContextValue>({
  language: 'en',
  t: (key) => key,
  plural: (n, key) => (n === 1 ? key : key),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState('en');

  useEffect(() => {
    const refresh = () => api.getSettings().then((s) => setLanguage(s.language || 'en')).catch(() => {});
    refresh();
    window.addEventListener('cognis:settings-changed', refresh);
    return () => window.removeEventListener('cognis:settings-changed', refresh);
  }, []);

  const t = (key: string, params?: Record<string, string | number>): string => {
    const dict = dictionaries[language] || en;
    let s = dict[key] ?? en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
    }
    return s;
  };

  const plural = (n: number, wordKey: 'word.concept' | 'word.question'): string => {
    const dict = dictionaries[language] || en;
    if (wordKey === 'word.concept') {
      return `${n} ${n === 1 ? dict['word.concept'] : dict['word.concepts']}`;
    }
    return `${n} ${n === 1 ? dict['word.question'] : dict['word.questions']}`;
  };

  const value: I18nContextValue = { language, t, plural };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function useTimeAgo() {
  const { t } = useI18n();
  return (dateStr: string | null | undefined): string => {
    if (!dateStr) return '';
    const diff = Date.now() - new Date(dateStr).getTime();
    const mins = Math.floor(diff / 60000);
    if (mins < 1) return t('time.justNow');
    if (mins < 60) return t('time.minAgo', { n: mins });
    const hours = Math.floor(mins / 60);
    if (hours < 24) return t('time.hourAgo', { n: hours });
    return t('time.dayAgo', { n: Math.floor(hours / 24) });
  };
}